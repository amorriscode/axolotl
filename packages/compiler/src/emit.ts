import { discriminator } from "./codec.ts";
import type { Loc } from "./diagnostics.ts";
import type {
  AccountParam,
  ArgParam,
  Idl,
  IdlAccount,
  InstructionModel,
  ProgramModel,
  Scalar,
  SeedModel,
  SourceMap,
  StructModel,
} from "./model.ts";
import { accountSpace, idlType, rustType, snake } from "./util.ts";

const SYSTEM_PROGRAM = "11111111111111111111111111111111";
const CLOCK = "SysvarC1ock11111111111111111111111111111111";
const RENT = "SysvarRent111111111111111111111111111111111";

export function emitRust(program: ProgramModel): { rust: string; sourceMap: SourceMap } {
  const lines: string[] = [];
  const sourceMap: SourceMap = { lines: {} };
  const push = (text: string, loc?: Loc) => {
    for (const line of text.split("\n")) {
      lines.push(line);
      if (loc) sourceMap.lines[lines.length] = loc;
    }
  };

  push("#![allow(unexpected_cfgs)]");
  push("// Generated by Axolotl. Edit the TypeScript source, then recompile.");
  push("use anchor_lang::prelude::*;");
  if (program.usesSpl) {
    push("use anchor_spl::token_interface::{Mint, TokenAccount, TokenInterface};");
  }
  push("");
  push(`declare_id!("${program.programId}");`);
  push("");
  push("#[program]");
  push(`pub mod ${program.rustName} {`);
  push("    use super::*;");
  push("");
  for (const instruction of program.instructions) {
    if (instruction.failed) continue;
    emitInstruction(instruction, push);
    push("");
  }
  push("}");
  push("");

  for (const struct of program.structs) emitStruct(struct, push);

  for (const instruction of program.instructions) {
    if (instruction.failed) continue;
    emitAccounts(instruction, program, push);
  }

  if (program.errors.length > 0) {
    push("#[error_code]");
    push("pub enum AxolotlError {");
    for (const error of program.errors) {
      push(`    #[msg(${JSON.stringify(error.msg)})]`);
      push(`    ${error.name},`);
    }
    push("}");
    push("");
  }

  if (program.usesRawCpi) emitCodec(push);

  return { rust: `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`, sourceMap };
}

function emitInstruction(
  instruction: InstructionModel,
  push: (text: string, loc?: Loc) => void,
): void {
  const args = instruction.params.filter((param): param is ArgParam => param.kind === "arg");
  const argList = args.map((arg) => `${arg.rustName}: ${rustType(arg.ty)}`).join(", ");
  const params = [`ctx: Context<${pascal(instruction.rustName)}>`, argList].filter(Boolean).join(", ");
  push(`    pub fn ${instruction.rustName}(${params}) -> Result<()> {`, instruction.loc);
  for (const stmt of instruction.body) {
    for (const line of stmt.code.split("\n")) {
      push(line.length ? `        ${line}` : "", stmt.loc);
    }
  }
  push("        Ok(())");
  push("    }");
}

function emitStruct(struct: StructModel, push: (text: string, loc?: Loc) => void): void {
  if (struct.kind === "account") {
    const space = accountSpace(struct.fields);
    push("#[account]", struct.loc);
    push(`pub struct ${struct.name} {`, struct.loc);
    for (const field of struct.fields) push(`    pub ${field.rustName}: ${rustType(field.ty)},`, field.loc);
    push("}");
    push(`impl ${struct.name} {`);
    push(`    pub const INIT_SPACE: usize = ${space};`);
    push("}");
  } else {
    push("#[event]", struct.loc);
    push(`pub struct ${struct.name} {`, struct.loc);
    for (const field of struct.fields) push(`    pub ${field.rustName}: ${rustType(field.ty)},`, field.loc);
    push("}");
  }
  push("");
}

function emitAccounts(
  instruction: InstructionModel,
  program: ProgramModel,
  push: (text: string, loc?: Loc) => void,
): void {
  const accounts = instruction.params.filter((param): param is AccountParam => param.kind === "account");
  const args = instruction.params.filter((param): param is ArgParam => param.kind === "arg");
  const usesArgSeed = accounts.some((account) => account.opts.seeds.some((seed) => seed.kind === "arg"));
  push("#[derive(Accounts)]");
  if (usesArgSeed) {
    const list = args.map((arg) => `${arg.rustName}: ${rustType(arg.ty)}`).join(", ");
    push(`#[instruction(${list})]`);
  }
  const structName = pascal(instruction.rustName);
  push(`pub struct ${structName}<'info> {`);
  for (const account of accounts) {
    const attr = accountAttr(account, program);
    if (account.accountKind === "unchecked" || account.accountKind === "program") {
      push("    /// CHECK: Axolotl does not verify this account's owner. Constraints above still apply.");
    }
    if (attr) push(`    #[account(${attr})]`);
    push(`    pub ${account.rustName}: ${accountRustType(account)},`);
  }
  push("}");
  push("");
}

function accountAttr(account: AccountParam, program: ProgramModel): string {
  const parts: string[] = [];
  const { opts } = account;
  if (opts.init) parts.push("init");
  if (opts.initIfNeeded) parts.push("init_if_needed");
  if (opts.payer) parts.push(`payer = ${snake(opts.payer)}`);
  if ((opts.init || opts.initIfNeeded) && account.accountType) {
    parts.push(`space = 8 + ${account.accountType}::INIT_SPACE`);
  }
  if (opts.mut && !opts.init && !opts.initIfNeeded) parts.push("mut");
  if (opts.seeds.length > 0) {
    const seeds = opts.seeds.map((seed) => seedRust(seed, program, instructionArgs(account, program))).join(", ");
    parts.push(`seeds = [${seeds}]`);
  }
  if (opts.bump) {
    const struct = program.structs.find((item) => item.name === account.accountType);
    const stored = struct?.fields.find((field) => field.name === "bump" && field.ty === "u8");
    if (stored && !opts.init && !opts.initIfNeeded) parts.push(`bump = ${account.rustName}.${stored.rustName}`);
    else parts.push("bump");
  }
  for (const rel of opts.hasOne) parts.push(`has_one = ${snake(rel)}`);
  if (opts.close) parts.push(`close = ${snake(opts.close)}`);
  return parts.join(", ");
}

function instructionArgs(account: AccountParam, program: ProgramModel): ArgParam[] {
  const instruction = program.instructions.find((item) => item.params.includes(account));
  return instruction?.params.filter((param): param is ArgParam => param.kind === "arg") ?? [];
}

function seedRust(seed: SeedModel, program: ProgramModel, args: ArgParam[]): string {
  if (seed.kind === "const") {
    const bytes = [...new TextEncoder().encode(seed.value)];
    const printable = [...seed.value].every((ch) => ch.charCodeAt(0) >= 32 && ch.charCodeAt(0) < 127 && ch !== "\\" && ch !== "\"");
    return printable ? `b${JSON.stringify(seed.value)}` : `&[${bytes.map((byte) => `${byte}u8`).join(", ")}]`;
  }
  if (seed.kind === "account") return `${snake(seed.name)}.key().as_ref()`;
  const arg = args.find((item) => item.name === seed.name);
  const name = arg?.rustName ?? snake(seed.name);
  const ty = arg?.ty ?? "u64";
  if (ty === "pubkey" || ty === "bytes32") return `${name}.as_ref()`;
  if (ty === "string") return `${name}.as_bytes()`;
  if (ty === "u8" || ty === "i8" || ty === "bool") return `&[${name} as u8]`;
  return `${name}.to_le_bytes().as_ref()`;
}

function accountRustType(account: AccountParam): string {
  switch (account.accountKind) {
    case "user":
      return `Account<'info, ${account.accountType}>`;
    case "signer":
      return "Signer<'info>";
    case "system":
      return "Program<'info, System>";
    case "tokenProgram":
      return "Interface<'info, TokenInterface>";
    case "tokenAccount":
      return "InterfaceAccount<'info, TokenAccount>";
    case "mint":
      return "InterfaceAccount<'info, Mint>";
    case "unchecked":
    case "program":
      return "UncheckedAccount<'info>";
    case "systemAccount":
      return "SystemAccount<'info>";
    case "clock":
      return "Sysvar<'info, Clock>";
    case "rent":
      return "Sysvar<'info, Rent>";
    default:
      return "UncheckedAccount<'info>";
  }
}

function emitCodec(push: (text: string, loc?: Loc) => void): void {
  push("#[allow(dead_code)]");
  push("mod ax_codec {");
  push("    use super::*;");
  const scalars: Scalar[] = ["u8", "u16", "u32", "u64", "u128", "i8", "i16", "i32", "i64", "i128", "bool", "string", "pubkey", "bytes32"];
  for (const scalar of scalars) {
    if (scalar === "bool") {
      push("    pub fn push_bool(data: &mut Vec<u8>, value: bool) { data.push(u8::from(value)); }");
    } else if (scalar === "string") {
      push("    pub fn push_string(data: &mut Vec<u8>, value: &str) {");
      push("        data.extend_from_slice(&(value.len() as u32).to_le_bytes());");
      push("        data.extend_from_slice(value.as_bytes());");
      push("    }");
    } else if (scalar === "pubkey") {
      push("    pub fn push_pubkey(data: &mut Vec<u8>, value: Pubkey) { data.extend_from_slice(value.as_ref()); }");
    } else if (scalar === "bytes32") {
      push("    pub fn push_bytes32(data: &mut Vec<u8>, value: &[u8; 32]) { data.extend_from_slice(value); }");
    } else {
      push(`    pub fn push_${scalar}(data: &mut Vec<u8>, value: ${scalar}) { data.extend_from_slice(&value.to_le_bytes()); }`);
    }
  }
  push("}");
  push("");
}

function pascal(snakeName: string): string {
  return snakeName.split("_").filter(Boolean).map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
}

export function emitIdl(program: ProgramModel): Idl {
  return {
    address: program.programId,
    metadata: {
      name: program.rustName,
      version: program.version,
      spec: "0.1.0",
      description: program.description || "Created with Axolotl",
    },
    instructions: program.instructions.filter((instruction) => !instruction.failed).map((instruction) => ({
      name: instruction.rustName,
      discriminator: discriminator("global", instruction.rustName),
      accounts: idlAccounts(instruction),
      args: instruction.params.filter((param): param is ArgParam => param.kind === "arg").map((arg) => ({
        name: arg.rustName,
        type: idlType(arg.ty),
      })),
    })),
    accounts: program.structs.filter((struct) => struct.kind === "account").map((struct) => ({
      name: struct.name,
      discriminator: discriminator("account", struct.name),
    })),
    types: program.structs.map((struct) => ({
      name: struct.name,
      type: {
        kind: "struct" as const,
        fields: struct.fields.map((field) => ({ name: field.rustName, type: idlType(field.ty) })),
      },
    })),
    events: program.structs.filter((struct) => struct.kind === "event").map((struct) => ({
      name: struct.name,
      discriminator: discriminator("event", struct.name),
    })),
    errors: program.errors.map((error, index) => ({
      code: 6000 + index,
      name: error.name,
      msg: error.msg,
    })),
  };
}

function idlAccounts(instruction: InstructionModel): IdlAccount[] {
  const params = instruction.params.filter((param): param is AccountParam => param.kind === "account");
  const accounts = params.map((account) => idlAccount(account));
  for (const account of params) {
    for (const relation of account.opts.hasOne) {
      const target = accounts.find((item) => item.name === snake(relation));
      if (!target) continue;
      target.relations = [...(target.relations ?? []), account.rustName];
    }
  }
  return accounts;
}

function idlAccount(account: AccountParam): IdlAccount {
  const writable = account.opts.mut || account.opts.init || account.opts.initIfNeeded || Boolean(account.opts.close);
  const signer = account.accountKind === "signer" || ((account.opts.init || account.opts.initIfNeeded) && account.opts.seeds.length === 0);
  const result: IdlAccount = { name: account.rustName };
  if (writable) result.writable = true;
  if (signer) result.signer = true;
  if (account.accountKind === "system") result.address = SYSTEM_PROGRAM;
  if (account.accountKind === "clock") result.address = CLOCK;
  if (account.accountKind === "rent") result.address = RENT;
  if (account.opts.seeds.length > 0) {
    result.pda = {
      seeds: account.opts.seeds.map((seed) => {
        if (seed.kind === "const") return { kind: "const" as const, value: [...new TextEncoder().encode(seed.value)] };
        if (seed.kind === "account") return { kind: "account" as const, path: snake(seed.name) };
        return { kind: "arg" as const, path: snake(seed.name) };
      }),
    };
  }
  return result;
}

export function emitClient(program: ProgramModel, idl: Idl): string {
  return `// Generated by Axolotl from ${program.name}. Do not edit.
import { decodeAccount, encodeInstruction } from "@axolotl-sol/client";

export const programId = ${JSON.stringify(program.programId)};
export const idl = ${JSON.stringify(idl, null, 2)} as const;

export function encode(name: string, args: Record<string, unknown> = {}): Uint8Array {
  return encodeInstruction(idl, name, args);
}

export function decode(account: string, data: Uint8Array): Record<string, unknown> {
  return decodeAccount(idl, account, data);
}
`;
}
